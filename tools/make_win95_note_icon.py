def image(grid: str) -> Image.Image:
    rows = grid.strip("\n").split("\n")
    n = len(rows)
    assert all(len(r) == n for r in rows), [len(r) for r in rows]
    img = Image.new("RGBA", (n, n))
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            img.putpixel((x, y), PALETTE[ch])
    return img


def write(family: str, base: Image.Image) -> None:
    n = base.size[0]
    out = os.path.join(ROOT, family)
    for factor in (1, 2, 3, 4):
        img = base if factor == 1 else base.resize((n * factor, n * factor), Image.NEAREST)
        img.save(os.path.join(out, f"note-{n * factor}.png"), optimize=True)


if __name__ == "__main__":
    write("large", image(LARGE))
    write("small", image(SMALL))
