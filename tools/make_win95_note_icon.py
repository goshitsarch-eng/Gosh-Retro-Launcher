#!/usr/bin/env python3
"""Draws the Win95 "note" icon (a sticky note) as clean-room 16-colour pixel art.

The large (32px) and small (16px) sources are separate designs in the Win95 icon grammar: black
outline, upper-left light, VGA palette, a checker-dithered fold. Writes assets/win95/large/note-32.png
and small/note-16.png plus the strict 2x/3x/4x nearest-neighbour variants the other icons have:

    python3 tools/make_win95_note_icon.py
"""
